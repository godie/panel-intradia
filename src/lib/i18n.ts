export const dictionaries: Record<Lang, Dict> = { es, en, zh, fr };

/**
 * Translate a key for the given language. Falls back to Spanish, then to
 * the key itself if the key is missing in both the target language and Spanish.
 */
export function translate(lang: Lang, key: string): string {
  return dictionaries[lang]?.[key] ?? dictionaries.es[key] ?? key;
}
